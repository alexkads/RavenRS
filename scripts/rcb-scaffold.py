#!/usr/bin/env python3
"""Writes the ComponentBook of every component still pending in RCB (#754), from its example in
the component gallery and the signatures of its builder methods.

    scripts/rcb-scaffold.py <rustdoc-json-folder>            # writes the book files
    scripts/rcb-scaffold.py <rustdoc-json-folder> --only A,B # only these components

The rustdoc JSON is the one scripts/public-api.py makes (`cargo +nightly rustdoc ... --output-format
json`), one file per crate. For each component listed in tools/raven-component-book/pendentes.json
that has an example in examples/component-gallery/src/samples/:

- the example's body becomes the render of its stories, with the first `<Name>::<constructor>(...)`
  and its chain of builder calls taken apart: each call that sets a setting the book can change (no
  argument, a `bool`, a number, words, or a variant of an enum, written as a literal) leaves the
  chain and is applied again from the story's `Args`, its literal becoming the setting's default;
- the builder methods the example does not call become settings too, when their default is known:
  calls with no argument (off unless called), `disabled`, `read_only`, `selected`, `loading`;
- the stories are the example, one per other variant of each enum setting, and one per common state.

The files are `crates/<crate>/src/book/<name>.rs`, listed between the `rcb-scaffold` markers of the
crate's `src/book.rs`. Generated files say so on their first line; a person or an agent reviews them
and may change anything: the script never writes over a file whose first line it did not write.
A component the script cannot handle stays pending; `--report` says why.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PENDING = ROOT / "tools/raven-component-book/pendentes.json"
SAMPLES = sorted((ROOT / "examples/component-gallery/src/samples").glob("*.rs"))
CATALOG = ROOT / "site/components/index.html"
MARK = "//! Generated by scripts/rcb-scaffold.py"
# The gallery's picture of a gradient, for the examples that show one.
PICTURE = """/// A gradient picture, as the component gallery draws one.
fn picture(hue: f32) -> ImageData {
    ImageData::from_fn(160, 90, move |x, y| {
        let (u, v) = (x as f32 / 160.0, y as f32 / 90.0);
        Color::rgb(0.2 + 0.6 * u * hue, 0.3 + 0.4 * v, 0.9 - 0.5 * u)
    })
    .unwrap_or_else(|| unreachable!("the size is not zero"))
}

"""
BEGIN, END = "// rcb-scaffold: begin", "// rcb-scaffold: end"
NUMBERS = {"f32", "f64", "usize", "u8", "u16", "u32", "u64", "i32", "i64", "isize"}
SAFE_BOOLS = {"disabled", "read_only", "selected", "loading"}
STATES = ["disabled", "loading", "read_only", "selected", "compact", "error", "empty", "open"]
# Calls that change what a component is about, not how it looks: never settings.
NOT_SETTINGS = {"new", "of", "test_id", "accessible_name", "accessible_description", "id", "key"}


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def families():
    out, family = {}, None
    for line in CATALOG.read_text().splitlines():
        if found := re.search(r'<h2 id="[^"]+">.*?#</a>(.*?)</h2>', line):
            family = found.group(1)
        elif (found := re.search(r'data-api="[^"]*">(\w+)</a><span class="sep"> - </span><span class="desc">(.*?)</span>', line)) and family:
            out.setdefault(found.group(1), (family, found.group(2)))
    return out


def samples():
    out = {}
    for path in SAMPLES:
        text = path.read_text()
        for found in re.finditer(r"^// sample: (\w+), \d+\n(.*?)^// end$", text, re.M | re.S):
            out[found.group(1)] = found.group(2)
    return out


def type_name(t):
    if not isinstance(t, dict):
        return str(t)
    if "primitive" in t:
        return t["primitive"]
    if "resolved_path" in t:
        rp = t["resolved_path"]
        return (rp.get("path") or rp.get("name") or "").split("::")[-1]
    if "borrowed_ref" in t:
        return "&" + type_name(t["borrowed_ref"]["type"])
    if "impl_trait" in t:
        for bound in t["impl_trait"]:
            tr = bound.get("trait_bound", {}).get("trait", {})
            name = (tr.get("path") or tr.get("name") or "").split("::")[-1]
            args = tr.get("args") or {}
            inner = ""
            if isinstance(args, dict) and "angle_bracketed" in args:
                got = args["angle_bracketed"].get("args", [])
                if got and isinstance(got[0], dict) and "type" in got[0]:
                    inner = type_name(got[0]["type"])
            if name:
                return f"impl {name}<{inner}>"
        return "impl ?"
    if "generic" in t:
        return t["generic"]
    return "?"


def read_api(folder):
    """Every struct's public inherent methods with their parameter types and whether they
    return Self, and every enum's variants."""
    structs, enums = {}, {}
    for file in sorted(Path(folder).glob("ravenrs_widgets*.json")):
        doc = json.loads(file.read_text())
        index = doc["index"]
        for item in index.values():
            inner = item.get("inner", {})
            name = item.get("name")
            if "enum" in inner and name:
                # Only variants with no data can be chosen by name.
                variants = [
                    index[str(v)]["name"]
                    for v in inner["enum"]["variants"]
                    if str(v) in index and index[str(v)]["inner"].get("variant", {}).get("kind") == "plain"
                ]
                if len(variants) >= 2:
                    enums.setdefault(name, variants)
            if "struct" in inner and name and name not in structs:
                methods = {}
                for impl_id in inner["struct"].get("impls", []):
                    impl = index.get(str(impl_id))
                    if not impl or impl["inner"]["impl"].get("trait"):
                        continue
                    for mid in impl["inner"]["impl"]["items"]:
                        m = index.get(str(mid))
                        if not m or "function" not in m.get("inner", {}) or m.get("visibility") != "public":
                            continue
                        sig = m["inner"]["function"]["sig"]
                        params = [type_name(t) for _, t in sig["inputs"]]
                        output = sig.get("output")
                        out = type_name(output) if output else ""
                        methods[m["name"]] = (params, out in ("Self", name))
                structs[name] = methods
    return structs, enums


def default_variant(enum):
    """The variant marked #[default] in the sources, if any."""
    for path in (ROOT / "crates").glob("ravenrs-widgets*/src/**/*.rs"):
        text = path.read_text()
        found = re.search(rf"pub enum {enum}\b[^{{]*\{{(.*?)\n\}}", text, re.S)
        if found:
            marked = re.search(r"#\[default\]\s*(?:///[^\n]*\n\s*)*(\w+)", found.group(1))
            return marked.group(1) if marked else None
    return None


def constructor_defaults(name, crate):
    """method -> literal default, read from the setter (`self.field = value`) and the constructor
    (`field: literal`) of the component's sources."""
    source = "\n".join(p.read_text() for p in (ROOT / "crates" / crate / "src").rglob("*.rs") if "/book/" not in str(p))
    at = re.search(rf"impl(?:<[^>]*>)? {name}(?:<[^>]*>)? \{{", source)
    if not at:
        return {}
    end = balanced(source, source.index("{", at.start()))
    body = source[at.start():end or len(source)]
    ctor = re.search(r"pub fn new\([^)]*\)[^{]*\{", body)
    fields = {}
    if ctor:
        cbody = body[ctor.end() - 1:balanced(body, ctor.end() - 1) or len(body)]
        for field, value in re.findall(r"\b(\w+): (true|false|-?\d+(?:\.\d+)?(?:_?f32)?|\w+::\w+)\s*[,}]", cbody):
            fields.setdefault(field, value)
    out = {}
    for method, param, field in re.findall(r"pub fn (\w+)\(mut self, (\w+): [^)]*\) -> Self \{\s*self\.(\w+)(?:\.\w+)? = (?:Some\()?", body):
        if field in fields:
            out[method] = fields[field]
    return out


def balanced(text, start):
    """The index just after the bracket that closes the one at `start`."""
    pairs = {"(": ")", "[": "]", "{": "}"}
    stack, i, quote = [], start, None
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 2
                continue
            if c == quote:
                quote = None
        elif c == '"':
            quote = c
        elif c in pairs:
            stack.append(pairs[c])
        elif c in ")]}":
            if not stack or stack.pop() != c:
                return None
            if not stack:
                return i + 1
        i += 1
    return None


def take_chain(body, name):
    """(start, end, constructor text, [(method, argument text)]) of the first `Name::ctor(...)`."""
    found = re.search(rf"\b{name}(?:::<[^>]*>)?::(\w+)\(", body)
    if not found:
        return None
    end = balanced(body, found.end() - 1)
    if end is None:
        return None
    ctor = body[found.start():end]
    calls, i = [], end
    while True:
        m = re.match(r"\s*\.(\w+)(?:::<[^>]*>)?\(", body[i:])
        if not m:
            break
        open_at = i + m.end() - 1
        close = balanced(body, open_at)
        if close is None:
            return None
        calls.append((m.group(1), body[open_at + 1:close - 1].strip(), body[i:close]))
        i = close
    return found.start(), i, ctor, calls


def literal(kind, arg, enums):
    """The default a literal argument gives, or None when it is not a literal of that kind."""
    if kind == "flag":
        return arg == ""
    if kind == "bool":
        return arg in ("true", "false")
    if kind == "num":
        return re.fullmatch(r"-?\d+(\.\d+)?(_?f32|_?f64|_?usize|_?u32)?", arg.replace("_", "")) is not None
    if kind == "text":
        return re.fullmatch(r'"(?:[^"\\]|\\.)*"', arg) is not None
    if kind == "choice":
        return re.fullmatch(r"\w+::\w+", arg) is not None
    return False


def kind_of(params, enums):
    rest = params[1:] if params and params[0] in ("self", "Self") else None
    if rest is None:
        return None, None
    if not rest:
        return "flag", None
    if len(rest) != 1:
        return None, None
    p = rest[0]
    if p == "bool":
        return "bool", None
    if p in NUMBERS:
        return "num", p
    if p in ("impl Into<String>", "impl Into<str>", "String", "&str") or p.startswith("impl Into<String"):
        return "text", None
    if p in enums and enums[p]:
        return "choice", p
    return None, None


def rust_str(s):
    return json.dumps(s)


def build(name, body, methods, enums, family, summary, known=None):
    known = known or {}
    chain = take_chain(body, name)
    if not chain:
        return None, "the example does not build it with Name::constructor(...)"
    start, end, ctor, calls = chain
    settings, kept, tail = [], [], []
    used = set()
    for method, arg, text in calls:
        # A call that is not the component's own (a modifier of every view, as `.padding`) wraps
        # it: it and what follows stay after the settings are applied.
        if tail or method not in methods:
            tail.append(text)
            continue
        params, returns_self = methods.get(method, (None, False))
        kind, ty = kind_of(params or [], enums)
        if method in NOT_SETTINGS or not returns_self or kind is None or method in used or not literal(kind, arg, enums):
            kept.append(text)
            continue
        used.add(method)
        if kind == "flag":
            settings.append(("flag", method, None, True))
        elif kind == "bool":
            settings.append(("bool", method, None, arg == "true"))
        elif kind == "num":
            value = float(re.sub(r"[a-z_]+$", "", arg.replace("_", "")) or 0)
            settings.append(("num", method, ty, value))
        elif kind == "text":
            settings.append(("text", method, None, json.loads(arg)))
        elif kind == "choice":
            enum, variant = arg.split("::")
            if enum != ty or variant not in enums[ty]:
                kept.append(text)
                used.discard(method)
                continue
            settings.append(("choice", method, ty, variant))
    for method, (params, returns_self) in sorted(methods.items()):
        if method in used or method in NOT_SETTINGS or not returns_self:
            continue
        kind, ty = kind_of(params, enums)
        if kind == "flag":
            settings.append(("flag", method, None, False))
        elif kind == "bool" and (method in known or method in SAFE_BOOLS):
            settings.append(("bool", method, None, known.get(method, "false") == "true"))
        elif kind == "choice":
            default = known.get(method, "").split("::")[-1] if "::" in known.get(method, "") else default_variant(ty)
            if default and default in enums[ty]:
                settings.append(("choice", method, ty, default))
            else:
                continue
        elif kind == "num" and method in known and re.fullmatch(r"-?\d+(\.\d+)?(_?f32)?", known[method]):
            settings.append(("num", method, ty, float(known[method].replace("_f32", "").replace("f32", ""))))
        elif kind == "text":
            settings.append(("optional-text", method, None, ""))
        else:
            continue
        used.add(method)
    # A component with no setting the book can change still gets its example as a story: it
    # is measured and listed, and the review adds settings by hand where the component has them.

    apply = [f"let mut it = {ctor}{''.join(kept)};"]
    upfront = []
    args_lines = []
    stories = ['.story("Example", Args::new())']
    for kind, method, ty, default in settings:
        if kind in ("flag", "bool"):
            call = "it = it.{m}();" if kind == "flag" else "it = it.{m}(true);"
            upfront.append(f"let arg_{method} = args.bool({rust_str(method)});")
            if kind == "bool":
                apply.append(f"it = it.{method}(arg_{method});")
            else:
                apply.append(f"if arg_{method} {{ it = it.{method}(); }}")
            args_lines.append(f".arg(ArgType::bool({rust_str(method)}, {'true' if default else 'false'}))")
            if method in STATES and not default:
                stories.append(f'.story({rust_str(method.replace("_", " ").capitalize())}, Args::new().with({rust_str(method)}, true))')
        elif kind == "num":
            cast = "" if ty == "f64" else f" as {ty}"
            upfront.append(f"let arg_{method} = args.number({rust_str(method)}){cast};")
            apply.append(f"it = it.{method}(arg_{method});")
            whole = ty not in ("f32", "f64")
            top = max(abs(default) * 4, 10.0 if whole else 1.0)
            low = 0.0 if default >= 0 else -top
            step = 1.0 if whole or top >= 50 else 0.1 if top >= 2 else 0.01
            args_lines.append(f".arg(ArgType::number({rust_str(method)}, {default!r}, {low!r}, {top!r}, {step!r}))")
        elif kind == "optional-text":
            upfront.append(f"let arg_{method} = args.text({rust_str(method)});")
            apply.append(f"if !arg_{method}.is_empty() {{ it = it.{method}(arg_{method}.clone()); }}")
            args_lines.append(f".arg(ArgType::text({rust_str(method)}, \"\").description(\"Empty leaves it as the component has it.\"))")
        elif kind == "text":
            upfront.append(f"let arg_{method} = args.text({rust_str(method)});")
            apply.append(f"it = it.{method}(arg_{method}.clone());")
            args_lines.append(f".arg(ArgType::text({rust_str(method)}, {rust_str(default)}))")
        elif kind == "choice":
            variants = enums[ty]
            arms = " ".join(f"{rust_str(v)} => {ty}::{v}," for v in variants if v != default)
            upfront.append(f"let arg_{method} = match args.choice({rust_str(method)}) {{ {arms} _ => {ty}::{default}, }};")
            apply.append(f"it = it.{method}(arg_{method}.clone());")
            options = ", ".join(rust_str(v) for v in variants)
            args_lines.append(f".arg(ArgType::choice({rust_str(method)}, &[{options}], {rust_str(default)}))")
            for v in variants:
                if v != default and len(stories) < 9:
                    label = f"{method.replace('_', ' ').capitalize()}: {v}"
                    stories.append(f".story({rust_str(label)}, Args::new().with({rust_str(method)}, ArgValue::choice({rust_str(v)})))")
    block = "{\n        " + "\n        ".join(apply) + "\n        it\n    }" + "".join(tail)
    rendered = body[:start] + block + body[end:]
    # The state the example starts in (`let open = State::new(false);`) becomes a setting, so a
    # story can show a dialog open, a box checked, a row chosen or words typed.
    taken = {m for _, m, _, _ in settings}
    def initial(match):
        var, value = match.group(1), match.group(2)
        setting = var if var not in taken else f"{var}_state"
        if setting in taken:
            return match.group(0)
        taken.add(setting)
        if value in ("true", "false"):
            args_lines.append(f".arg(ArgType::bool({rust_str(setting)}, {value}).description(\"How the example starts.\"))")
            if value == "false" and len(stories) < 9:
                stories.append(f".story({rust_str(setting.replace('_', ' ').capitalize())}, Args::new().with({rust_str(setting)}, true))")
            return f"let {var} = State::new(args.bool({rust_str(setting)}));"
        if re.fullmatch(r"\d+(usize|u32|i32)?", value):
            n = int(re.sub(r"[a-z].*", "", value))
            args_lines.append(f".arg(ArgType::number({rust_str(setting)}, {float(n)!r}, 0.0, {float(max(n * 4, 5))!r}, 1.0).description(\"How the example starts.\"))")
            return f"let {var} = State::new(args.number({rust_str(setting)}) as _);"
        found = re.fullmatch(r'String::from\(("(?:[^"\\]|\\.)*")\)|("(?:[^"\\]|\\.)*")\.to_owned\(\)|("(?:[^"\\]|\\.)*")\.to_string\(\)', value)
        if found:
            text = next(g for g in found.groups() if g)
            args_lines.append(f".arg(ArgType::text({rust_str(setting)}, {text}).description(\"How the example starts.\"))")
            return f"let {var} = State::new(args.text({rust_str(setting)}));"
        return match.group(0)
    def initial_top(match):
        # Only the example's own statements: a function inside it cannot see the settings.
        depth = sum((c in "{([") - (c in "})]") for c in rendered[: match.start()])
        return initial(match) if depth == 1 else match.group(0)
    rendered = re.sub(r"let (\w+) = State::new\((true|false|\d+(?:usize|u32|i32)?|String::from\(\"(?:[^\"\\\\]|\\\\.)*\"\)|\"(?:[^\"\\\\]|\\\\.)*\"\.to_(?:owned|string)\(\))\);", initial_top, rendered)
    inner = rendered.strip()
    # The example's body, `{ ... }` of `fn x() -> impl View`, drawn from the settings.
    found = re.match(r"fn \w+\(\) -> impl View \{(.*)\}\s*$", inner, re.S)
    if not found:
        return None, "the example is not `fn name() -> impl View { ... }`"
    code = "\n".join("    " + line for line in upfront) + "\n" + found.group(1).rstrip()
    # The facade's paths, as the gallery writes them, by the crates the component's crate has.
    for facade, crate_path in (("ravenrs::core::", "ravenrs_core::"), ("ravenrs::layout::", "ravenrs_layout::"),
                               ("ravenrs::style::", "ravenrs_style::"), ("ravenrs::reactive::", "ravenrs_reactive::"),
                               ("ravenrs::prelude::", ""), ("ravenrs::widgets::", "")):
        code = code.replace(facade, crate_path)
    helper = PICTURE if "picture(" in code else ""
    title = f"{family}/{name}"
    summary = summary.rstrip(".") + "."
    text = f"""{MARK} from the component gallery's example of `{name}`; review it, then
//! remove this line so the script no longer writes over it.

#[allow(unused_imports)]
use std::collections::{{BTreeMap, BTreeSet, HashMap}};
#[allow(unused_imports)]
use std::rc::Rc;
#[allow(unused_imports)]
use ravenrs_core::*;
#[allow(unused_imports)]
use ravenrs_layout::*;
#[allow(unused_imports)]
use ravenrs_reactive::*;
#[allow(unused_imports)]
use ravenrs_style::*;
{{imports}}
#[allow(unused_imports)]
use {{book}}::{{ArgType, ArgValue, Args, ComponentBook, Meta}};

{helper}/// The gallery's example of `{name}`, with its settings taken from the story.
#[allow(unused_variables, unused_mut, clippy::redundant_clone, clippy::let_and_return, clippy::clone_on_copy)]
fn render(args: &Args) -> AnyView {{
    Box::new({{
{code}
    }})
}}

impl ComponentBook for {{target}} {{
    fn book() -> Meta {{
        Meta::new({rust_str(title)}, render)
            .summary({rust_str(summary)})
            {chr(10).join("            " + a for a in args_lines).lstrip()}
            {chr(10).join("            " + s for s in stories).lstrip()}
    }}
}}
"""
    # A component with no settings leaves a line of spaces where they would be.
    text = re.sub(r"\n[ \t]+\n", "\n", text)
    return text, None


def main():
    folder = sys.argv[1]
    only = None
    skip = {}
    if "--skip" in sys.argv:
        skip = json.loads(Path(sys.argv[sys.argv.index("--skip") + 1]).read_text())
    if "--only" in sys.argv:
        only = set(sys.argv[sys.argv.index("--only") + 1].split(","))
    structs, enums = read_api(folder)
    pending = json.loads(PENDING.read_text())["pendentes"]
    # Files written before and not yet reviewed are written again, with what the script knows now.
    listed = {(e["crate"], e["tipo"]) for e in pending}
    for path in sorted((ROOT / "crates").glob("ravenrs-widgets*/src/book/*.rs")):
        text = path.read_text()
        found = re.search(r"impl ComponentBook for (\w+)", text)
        crate = path.parent.parent.parent.name
        if text.startswith(MARK) and found and (crate, found.group(1)) not in listed:
            pending.append({"crate": crate, "tipo": found.group(1)})
    fams, examples = families(), samples()
    report = {}
    for entry in pending:
        crate, name = entry["crate"], entry["tipo"]
        if only and name not in only:
            continue
        if name not in examples:
            report[name] = "no example in the component gallery"
            continue
        if name in skip:
            report[name] = skip[name]
            path = ROOT / "crates" / crate / "src/book" / f"{snake(name)}.rs"
            if path.exists() and path.read_text().startswith(MARK):
                path.unlink()
            continue
        family, summary = fams.get(name, ("Data" if name.startswith("Flow") else "Media", name))
        text, why = build(name, examples[name], structs.get(name, {}), enums, family, summary, constructor_defaults(name, crate))
        if not text:
            report[name] = why
            continue
        base = crate == "ravenrs-widgets-base"
        imports = "#[allow(unused_imports)]\nuse crate::*;" if base else (
            "#[allow(unused_imports)]\nuse crate::*;\n#[allow(unused_imports)]\nuse ravenrs_widgets_base::*;\n"
            "#[allow(unused_imports)]\nuse ravenrs_widgets_kit::*;" if crate != "ravenrs-widgets-kit" else
            "#[allow(unused_imports)]\nuse crate::*;\n#[allow(unused_imports)]\nuse ravenrs_widgets_base::*;")
        text = text.replace("{imports}", imports).replace("{book}", "crate::book" if base else "ravenrs_widgets_base::book")
        source = "\n".join(p.read_text() for p in (ROOT / "crates" / crate / "src").rglob("*.rs") if "/book/" not in str(p))
        target = name
        # A generic component takes a view for each parameter, or a tuple of one where the
        # parameter is a sequence of views, as its own `impl View` asks.
        view_impl = re.search(rf"impl<([^>]*(?:<[^>]*>[^>]*)*)> View for {name}<([^>]*)>", source)
        if view_impl:
            bounds = {}
            for part in re.split(r",(?![^<]*>)", view_impl.group(1)):
                if ":" in part:
                    key, bound = part.split(":", 1)
                    bounds[key.strip()] = bound
            params = [g.strip() for g in view_impl.group(2).split(",") if g.strip() and not g.strip().startswith("'")]
            chosen = []
            for g in params:
                if g in bounds and "ViewSeq" in bounds[g]:
                    chosen.append("(AnyView,)")
                elif re.fullmatch(r"[A-Z]\w*", g) and g in bounds or len(g) == 1:
                    chosen.append("AnyView")
                else:
                    chosen.append(g)
            target = f"{name}<{', '.join(chosen)}>"
        text = text.replace("{target}", target)
        path = ROOT / "crates" / crate / "src/book" / f"{snake(name)}.rs"
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and not path.read_text().startswith(MARK):
            report[name] = f"{path.relative_to(ROOT)} was reviewed: left as it is"
            continue
        path.write_text(text)
        report[name] = "written"
    register()
    json.dump(report, sys.stdout, indent=1, ensure_ascii=False)


def register():
    """Lists every generated file in its crate's `src/book.rs`, between the markers, and makes
    the `book` module and feature of the crates that had none."""
    for crate_dir in sorted((ROOT / "crates").glob("ravenrs-widgets-*")):
        folder = crate_dir / "src/book"
        book = crate_dir / "src/book.rs"
        # Every file of the book that gives a component its stories, generated or reviewed,
        # except the ones the crate's book.rs declares by hand, outside the markers.
        by_hand = set()
        if book.exists():
            outside = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", book.read_text(), flags=re.S)
            by_hand = set(re.findall(r"^mod (\w+);", outside, re.M))
        generated = sorted(
            p for p in folder.glob("*.rs") if p.stem not in by_hand and "impl ComponentBook for" in p.read_text()
        ) if folder.is_dir() else []
        if not generated:
            continue
        types = []
        for path in generated:
            found = re.search(r"impl ComponentBook for (\w+(?:<[^>]*>)?)", path.read_text())
            if found:
                types.append((path.stem, found.group(1)))
        # A component behind a feature where its crate re-exports it is behind it here too.
        lib = (crate_dir / "src/lib.rs").read_text()
        def gate(ty):
            name = ty.split("<")[0]
            found = re.search(r'#\[cfg\((feature = "[^"]+")\)\]\s*pub use [^;]*\b' + name + r'\b[^;]*;', lib)
            return f"#[cfg({found.group(1)})]\n" if found else ""
        mods = "\n".join(f"{gate(ty)}mod {stem};" for stem, ty in types)
        trait = "ComponentBook" if crate_dir.name == "ravenrs-widgets-base" else "ravenrs_widgets_base::book::ComponentBook"
        pushes = "\n".join(f"    {gate(ty).strip() + chr(10) + '    ' if gate(ty) else ''}all.push(<crate::{ty} as {trait}>::book());" for _, ty in types)
        uses = "" if crate_dir.name == "ravenrs-widgets-base" else "#[allow(unused_imports)]\nuse ravenrs_widgets_base::AnyView;\n"
        block = f"{BEGIN}\n{mods}\n{uses}\n/// The stories written by scripts/rcb-scaffold.py, in name order.\npub(crate) fn generated() -> Vec<Meta> {{\n    let mut all = Vec::new();\n{pushes}\n    all\n}}\n{END}"
        if not book.exists():
            crate = crate_dir.name
            book.write_text(
                f"//! The stories of the components of this crate, for RavenComponentBook: see\n"
                f"//! `ravenrs_widgets_base::book`.\n\n"
                f"#[allow(unused_imports)]\nuse ravenrs_widgets_base::book::{{ComponentBook, Meta}};\n\n"
                f"/// The stories of the components of this crate that give them, in the order the book lists\n"
                f"/// them.\npub fn stories() -> Vec<Meta> {{\n    generated()\n}}\n\n{block}\n"
            )
            lib = crate_dir / "src/lib.rs"
            text = lib.read_text()
            if "pub mod book;" not in text:
                first = re.search(r"^(#\[|pub mod |mod |use )", text, re.M)
                at = first.start() if first else len(text)
                text = text[:at] + '/// The stories of the components of this crate (feature `book`).\n#[cfg(feature = "book")]\npub mod book;\n\n' + text[at:]
                lib.write_text(text)
            cargo = crate_dir / "Cargo.toml"
            ctext = cargo.read_text()
            if "\nbook = " not in ctext:
                deps = ["ravenrs-widgets-base/book", "ravenrs-widgets-kit/book"]
                ctext = ctext.replace("[features]\n", "[features]\n# The stories of its components, for RavenComponentBook (`book::stories`).\nbook = [" + ", ".join(f'\"{d}\"' for d in deps) + "]\n", 1)
                cargo.write_text(ctext)
        else:
            text = book.read_text()
            if BEGIN in text:
                text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, text, flags=re.S)
            else:
                text = text.rstrip() + "\n\n" + block + "\n"
            book.write_text(text)


main()

use crate::{TOOLCHAIN, VERSION, configure_ai, read, run, write};
use ravenrs_project::{Project, ProjectFile};
use std::path::Path;
use toml_edit::{DocumentMut, Item, Value, value};

const WORKSPACE: &str = include_str!("../../../Cargo.toml");
macro_rules! example {
    ($name:literal) => {
        (
            include_str!(concat!("../../../examples/", $name, "/Cargo.toml")),
            include_str!(concat!("../../../examples/", $name, "/src/lib.rs")),
        )
    };
}

/// Render a template without writing anything. Sources come directly from the examples.
pub fn project_files(name: &str, template: &str, target: &str) -> Result<Vec<ProjectFile>, String> {
    if !valid_name(name) {
        return Err("Nome inválido: use uma letra, seguida de letras ASCII, números, - ou _.".into());
    }
    if !matches!(target, "desktop" | "web" | "both") {
        return Err("Alvo inválido: desktop, web ou both.".into());
    }
    let (manifest, source) = match template {
        "hello" => example!("hello-world"),
        "app" => example!("tutorial-tasks"),
        "app-sqlite" => example!("tasks-sqlite"),
        "relatorios" => example!("report-designer"),
        _ => return Err("Modelo inválido: hello, app, app-sqlite ou relatorios.".into()),
    };
    let project = Project::new(name).source(source);
    let normalized = project.crate_name().replace('-', "_");
    let krate = name.replace('-', "_");
    let mut files = project.files_from_app();
    // Playground titles are normalized; Cargo names keep case and repeated separators.
    for file in &mut files {
        let suffix = match file.path.as_str() {
            "src/main.rs" => Some((format!("{normalized}::app()"), format!("{krate}::app()"))),
            "web/index.html" => Some((format!("pkg/{normalized}.js"), format!("pkg/{krate}.js"))),
            "README.md" => Some((format!("/{normalized}.wasm"), format!("/{krate}.wasm"))),
            _ => None,
        };
        if let Some((from, to)) = suffix {
            file.contents = file.contents.replace(&from, &to);
        }
    }
    let mut manifest: DocumentMut = manifest.parse().map_err(|e| format!("Modelo: {e}"))?;
    let workspace: DocumentMut = WORKSPACE.parse().map_err(|e| format!("Workspace: {e}"))?;
    manifest["package"]["name"] = value(name);
    manifest["package"]["version"] = value("0.1.0");
    for key in ["edition", "rust-version", "license"] {
        if manifest["package"][key].get("workspace").and_then(Item::as_bool) == Some(true) {
            manifest["package"][key] = workspace["workspace"]["package"][key].clone();
        }
    }
    manifest.as_table_mut().remove("lints");
    manifest.as_table_mut().remove("dev-dependencies");
    resolve_dependencies(&mut manifest["dependencies"], &workspace)?;
    if let Some(targets) = manifest.get_mut("target").and_then(Item::as_table_mut) {
        for (_, item) in targets.iter_mut() {
            // Tests of the example, such as recording its video, are not part of the new project.
            if let Some(table) = item.as_table_like_mut() {
                table.remove("dev-dependencies");
            }
            resolve_dependencies(&mut item["dependencies"], &workspace)?;
        }
        if target == "desktop" {
            targets.remove("cfg(target_arch = \"wasm32\")");
        }
    }
    let manifest = format!("# Generated by cargo-ravenrs {VERSION}\n{manifest}");
    for file in &mut files {
        if file.path == "Cargo.toml" {
            file.contents = manifest.clone();
        }
        if file.path == "README.md" {
            file.contents = file.contents.replace(
                "Made in the RavenRS playground.",
                &format!("Generated by cargo-ravenrs {VERSION} ({template}, {target})."),
            );
        }
    }
    if target == "desktop" {
        files.retain(|f| f.path != "web/index.html");
    }
    let mut toolchain: DocumentMut = TOOLCHAIN.parse().map_err(|e| format!("Toolchain: {e}"))?;
    if target == "desktop" {
        toolchain["toolchain"].as_table_mut().ok_or("toolchain inválida")?.remove("targets");
    }
    files.push(ProjectFile {
        path: "rust-toolchain.toml".into(),
        contents: format!("# cargo-ravenrs {VERSION}\n{toolchain}"),
    });
    files.push(ProjectFile {
        path: "tests/screen.rs".into(),
        contents: format!(
            r#"// cargo-ravenrs {VERSION}
#[test]
fn main_screen_renders() {{
    use ravenrs::prelude::*;
    let mut ui = Ui::new({krate}::app(), Theme::raven_dark());
    ui.set_viewport(ravenrs::core::Size::new(1200.0, 800.0), 1.0);
    ui.update();
    assert!(!ui.scene().primitives().is_empty());
}}
"#,
            krate = name.replace('-', "_")
        ),
    });
    Ok(files)
}

fn valid_name(name: &str) -> bool {
    const RESERVED: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if",
        "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self",
        "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
        "await", "dyn", "abstract", "become", "box", "do", "final", "gen", "macro", "override", "priv",
        "typeof", "unsized", "virtual", "yield", "try", "test", "lib", "std", "core", "alloc", "con", "prn",
        "aux", "nul",
    ];
    let lower = name.to_ascii_lowercase();
    name.as_bytes().first().is_some_and(u8::is_ascii_alphabetic)
        && name.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'-' || c == b'_')
        && !RESERVED.contains(&name)
        && !RESERVED.contains(&lower.as_str())
        && !(lower.len() == 4
            && (lower.starts_with("com") || lower.starts_with("lpt"))
            && lower.as_bytes()[3].is_ascii_digit())
}

fn resolve_dependencies(item: &mut Item, workspace: &DocumentMut) -> Result<(), String> {
    let Some(deps) = item.as_table_mut() else {
        return Ok(());
    };
    for (name, dependency) in deps.iter_mut() {
        if dependency.get("workspace").and_then(Item::as_bool) != Some(true) {
            continue;
        }
        let original = dependency.clone();
        *dependency = workspace["workspace"]["dependencies"]
            .get(&*name)
            .ok_or_else(|| format!("Dependência ausente: {name}"))?
            .clone();
        if let Some(table) = dependency.as_inline_table_mut() {
            table.remove("path");
            if let Some(extra) = original.get("features").and_then(Item::as_array) {
                let features = table
                    .entry("features")
                    .or_insert(Value::Array(Default::default()))
                    .as_array_mut()
                    .ok_or("features inválidas")?;
                for feature in extra.iter() {
                    features.push(feature.clone());
                }
            }
        } else if let Some(version) = dependency.as_str() {
            let mut table = toml_edit::InlineTable::new();
            table.insert("version", version.into());
            if let Some(features) = original.get("features").and_then(Item::as_value) {
                table.insert("features", features.clone());
            }
            *dependency = Item::Value(Value::InlineTable(table));
        }
        if name.starts_with("ravenrs") {
            dependency["version"] = value(format!("={VERSION}"));
        }
    }
    Ok(())
}

/// Create a project, optionally initialize Git and AI, check every chosen target and probe MCP.
pub fn new_project(
    path: &Path,
    template: &str,
    target: &str,
    git: bool,
    ai: bool,
    check: bool,
    plugin: bool,
) -> Result<(), String> {
    let name = path.file_name().and_then(|s| s.to_str()).ok_or("Nome de projeto inválido")?;
    let files = project_files(name, template, target)?;
    if path.exists() {
        // Never overwrite user code, including on repeated bootstrap runs.
        let expected = format!("# Generated by cargo-ravenrs {VERSION}");
        if !path.join("Cargo.toml").is_file() || !read(&path.join("Cargo.toml"))?.starts_with(&expected) {
            return Err(format!("{} já existe e não foi gerado por esta versão.", path.display()));
        }
        let state: DocumentMut = read(&path.join(".ravenrs-project.toml"))?
            .parse()
            .map_err(|e| format!("Metadados do projeto inválidos: {e}"))?;
        let previous_template =
            state.get("template").and_then(Item::as_str).ok_or("Modelo original ausente nos metadados")?;
        let previous_target =
            state.get("target").and_then(Item::as_str).ok_or("Alvo original ausente nos metadados")?;
        if previous_template != template || previous_target != target {
            return Err(format!(
                "{} já contém um projeto {previous_template}/{previous_target}; você escolheu {template}/{target}. Use outra pasta para criar esse modelo/alvo. O projeto existente não foi alterado.",
                path.display()
            ));
        }
        println!("Projeto existente: preservando o código.");
    } else {
        std::fs::create_dir_all(path).map_err(|e| e.to_string())?;
        for file in files {
            write(path, &file.path, &file.contents)?;
        }
        write(
            path,
            ".ravenrs-project.toml",
            &format!(
                "# cargo-ravenrs {VERSION}\nversion = \"{VERSION}\"\ntemplate = \"{template}\"\ntarget = \"{target}\"\nai = {ai}\n"
            ),
        )?;
    }
    if git && !path.join(".git").exists() {
        run(path, "git", &["init"])?;
    }
    if ai {
        configure_ai(path, plugin)?;
    }
    if check {
        if target != "web" {
            run(path, "cargo", &["check"])?;
        }
        if target != "desktop" {
            run(path, "cargo", &["check", "--target", "wasm32-unknown-unknown"])?;
        }
    }
    crate::mcp::probe("cargo", &["ravenrs".into(), "mcp".into()], path)?;
    let next = if target == "web" {
        "cargo check --target wasm32-unknown-unknown  # veja README.md para servir web/"
    } else {
        "cargo run"
    };
    println!("Pronto.\n  cd {}\n  {next}\n  claude  # ou code .\n  cargo ravenrs doctor", path.display());
    Ok(())
}

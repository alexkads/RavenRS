use crate::{SKILL, VERSION, read, write};
use serde_json::{Value, json};
use std::path::Path;
use toml_edit::{DocumentMut, value};

const START: &str = "<!-- ravenrs:begin -->";
const END: &str = "<!-- ravenrs:end -->";
const TOML_START: &str = "# ravenrs:begin";
const TOML_END: &str = "# ravenrs:end";

fn marked(previous: &str, body: &str, start: &str, end: &str) -> Result<String, String> {
    let block = format!("{start}\n{body}\n{end}");
    match (previous.find(start), previous.find(end)) {
        (Some(a), Some(b))
            if b > a
                && !previous[a + start.len()..].contains(start)
                && !previous[b + end.len()..].contains(end) =>
        {
            Ok(format!("{}{}{}", &previous[..a], block, &previous[b + end.len()..]))
        }
        (None, None) => Ok(format!(
            "{previous}{}{block}\n",
            if previous.is_empty() || previous.ends_with('\n') { "" } else { "\n" }
        )),
        _ => Err("Bloco RavenRS incompleto ou duplicado; corrija os marcadores antes de atualizar.".into()),
    }
}

fn previous(root: &Path, path: &str) -> Result<String, String> {
    if root.join(path).exists() { read(&root.join(path)) } else { Ok(String::new()) }
}

fn json_file(root: &Path, path: &str) -> Result<Value, String> {
    let old = previous(root, path)?;
    if old.is_empty() {
        return Ok(json!({}));
    }
    let parsed: Value = serde_json::from_str(&old).map_err(|e| format!("{path}: {e}"))?;
    if !parsed.is_object() {
        return Err(format!("{path}: objeto JSON esperado"));
    }
    Ok(parsed)
}

/// Prepare AI configuration without changing anything outside RavenRS-owned entries or blocks.
/// JSON is merged by key; Markdown and Codex TOML use explicit managed blocks.
pub fn configure_ai(root: &Path, plugin: bool) -> Result<(), String> {
    let files = ai_files(root, plugin)?;
    let skill = root.join(".claude/skills/ravenrs/SKILL.md");
    let remove_skill = plugin && skill.is_file();
    if remove_skill && read(&skill)? != SKILL {
        return Err("A skill local tem alterações. Mova suas notas antes de trocar para --plugin.".into());
    }
    for (path, contents) in files {
        write(root, &path, &contents)?;
    }
    if remove_skill {
        std::fs::remove_file(skill).map_err(|e| e.to_string())?;
    }
    println!("Arquivos de IA atualizados para RavenRS {VERSION}.");
    Ok(())
}

pub(crate) fn ai_files(root: &Path, plugin: bool) -> Result<Vec<(String, String)>, String> {
    let _ = read(&root.join("Cargo.toml"))?;
    let mut files = Vec::new();
    for (path, key, vscode) in [
        (".mcp.json", "mcpServers", false),
        (".cursor/mcp.json", "mcpServers", false),
        (".vscode/mcp.json", "servers", true),
    ] {
        let mut config = json_file(root, path)?;
        let mut server = json!({"command":"cargo", "args":["ravenrs", "mcp"]});
        if vscode {
            server["type"] = json!("stdio");
        }
        if config.get(key).is_some_and(|v| !v.is_object()) {
            return Err(format!("{path}: {key} deve ser um objeto"));
        }
        if config.get(key).is_none() {
            config[key] = json!({});
        }
        config[key]["ravenrs"] = server;
        config["$comment"] = json!(format!("cargo-ravenrs {VERSION}; managed entry: {key}.ravenrs"));
        files.push((
            path.into(),
            format!("{}\n", serde_json::to_string_pretty(&config).map_err(|e| e.to_string())?),
        ));
    }
    let path = ".codex/config.toml";
    let old = previous(root, path)?;
    let mut doc: DocumentMut =
        if old.is_empty() { DocumentMut::new() } else { old.parse().map_err(|e| format!("{path}: {e}"))? };
    if !old.contains(TOML_START) {
        // Adopt only the RavenRS table; preserve all unrelated settings and comments.
        if let Some(servers) = doc.get_mut("mcp_servers").and_then(toml_edit::Item::as_table_mut) {
            servers.remove("ravenrs");
        }
    }
    let old = if old.contains(TOML_START) { old } else { doc.to_string() };
    let body = format!(
        "# cargo-ravenrs {VERSION}\n[mcp_servers.ravenrs]\ncommand = \"cargo\"\nargs = [\"ravenrs\", \"mcp\"]"
    );
    let contents = marked(&old, &body, TOML_START, TOML_END)?;
    let _: DocumentMut = contents.parse().map_err(|e| format!("{path}: {e}"))?;
    files.push((path.into(), contents));

    let manifest: DocumentMut =
        read(&root.join("Cargo.toml"))?.parse().map_err(|e| format!("Cargo.toml: {e}"))?;
    let name = manifest["package"]["name"].as_str().unwrap_or("app").replace('-', "_");
    let web = root.join("web/index.html").is_file();
    let body = format!(
        r#"Generated by cargo-ravenrs {VERSION}.

Run: `cargo run`. Test: `cargo test`. Check: `cargo check`.
{web_commands}
The main screen is `src/lib.rs` (`app()`); the desktop entry point is `src/main.rs`.
Before writing API calls, consult the RavenRS MCP (`component_api`, `component_examples`).
Use semantic design tokens, library components and `ravenrs-app` for record lists and forms.
Never invent a method without checking the MCP. Keep project-specific instructions outside this block.
"#,
        web_commands = if web {
            format!(
                "Web: `cargo check --target wasm32-unknown-unknown`.\nBuild: `cargo build --release --lib --target wasm32-unknown-unknown`.\nInstall `wasm-bindgen-cli --version {}` with cargo, then run `wasm-bindgen --target web --out-dir web/pkg target/wasm32-unknown-unknown/release/{name}.wasm` and serve `web/` over HTTP.",
                ravenrs_project::WASM_BINDGEN_VERSION
            )
        } else {
            String::new()
        }
    );
    files.push(("AGENTS.md".into(), marked(&previous(root, "AGENTS.md")?, &body, START, END)?));
    files.push((
        "CLAUDE.md".into(),
        marked(&previous(root, "CLAUDE.md")?, &format!("cargo-ravenrs {VERSION}\n\n@AGENTS.md"), START, END)?,
    ));

    let path = ".claude/settings.json";
    let mut settings = json_file(root, path)?;
    settings["$comment"] = json!(format!("cargo-ravenrs {VERSION}"));
    if settings.get("enabledMcpjsonServers").is_none() {
        settings["enabledMcpjsonServers"] = json!([]);
    }
    let servers =
        settings["enabledMcpjsonServers"].as_array_mut().ok_or("enabledMcpjsonServers deve ser uma lista")?;
    if !servers.iter().any(|v| v.as_str() == Some("ravenrs")) {
        servers.push(json!("ravenrs"));
    }
    if settings.get("permissions").is_none() {
        settings["permissions"] = json!({});
    }
    if !settings["permissions"].is_object() {
        return Err("permissions deve ser um objeto".into());
    }
    if settings["permissions"].get("allow").is_none() {
        settings["permissions"]["allow"] = json!([]);
    }
    let allow =
        settings["permissions"]["allow"].as_array_mut().ok_or("permissions.allow deve ser uma lista")?;
    for rule in ["Bash(cargo check *)", "Bash(cargo test *)", "Bash(cargo run *)", "mcp__ravenrs__*"] {
        if !allow.iter().any(|v| v.as_str() == Some(rule)) {
            allow.push(json!(rule));
        }
    }
    if plugin {
        if settings.get("extraKnownMarketplaces").is_none() {
            settings["extraKnownMarketplaces"] = json!({});
        }
        if settings.get("enabledPlugins").is_none() {
            settings["enabledPlugins"] = json!({});
        }
        if !settings["extraKnownMarketplaces"].is_object() || !settings["enabledPlugins"].is_object() {
            return Err("Configuração de plugins inválida".into());
        }
        settings["extraKnownMarketplaces"]["ravenrs"] =
            json!({"source":{"source":"github","repo":"alexkads/RavenRS","ref":format!("v{VERSION}")}});
        settings["enabledPlugins"]["ravenrs@ravenrs"] = json!(true);
    } else {
        // The skill remains byte-for-byte equal to its versioned plugin source.
        let path = ".claude/skills/ravenrs/SKILL.md";
        let old = previous(root, path)?;
        let skill = if old.is_empty() {
            SKILL.into()
        } else {
            let start = "<!-- ravenrs:skill:begin -->";
            let end = "<!-- ravenrs:skill:end -->";
            if !old.contains(start) {
                return Err(format!(
                    "{path}: skill sem marcadores; preserve seu conteúdo antes de adotar a skill gerenciada."
                ));
            }
            let a = SKILL.find(start).ok_or("Skill sem marcador inicial")? + start.len();
            let b = SKILL.find(end).ok_or("Skill sem marcador final")?;
            marked(&old, SKILL[a..b].trim_matches('\n'), start, end)?
        };
        files.push((path.into(), skill));
        if let Some(plugins) = settings.get_mut("enabledPlugins").and_then(Value::as_object_mut) {
            plugins.remove("ravenrs@ravenrs");
        }
    }
    files.push((
        path.into(),
        format!("{}\n", serde_json::to_string_pretty(&settings).map_err(|e| e.to_string())?),
    ));
    // State is separate so doctor can honor --plugin and --no-ai without guessing.
    let mut state = DocumentMut::new();
    state["version"] = value(VERSION);
    state["plugin"] = value(plugin);
    files.push((".ravenrs-ai.toml".into(), format!("# cargo-ravenrs {VERSION}\n{state}")));
    Ok(files)
}
